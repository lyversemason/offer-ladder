-- Accounts and the audit log in live mode (docs/accounts-plan.md, phase 5).
--
-- audit_log: who did what to whom, when: every account change, rule change and
-- catalog import, written in the same transaction as the change itself. Only
-- admins can read it; nobody can change or delete a row (no grant, and a trigger).
--
-- The server function (server/save.ts) works out each account change with
-- src/data/accounts.ts and writes it with apply_account_change. save_settings and
-- apply_catalog_changes now write their audit entry too.

CREATE TABLE audit_log (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  actor_id  TEXT NOT NULL REFERENCES profiles (id),
  action    TEXT NOT NULL CHECK (action IN (
              'invited', 'invite_resent', 'invite_cancelled', 'invite_accepted', 'turned_off',
              'turned_on', 'access_changed', 'rules_changed', 'catalog_imported')),
  target_id TEXT REFERENCES profiles (id),
  detail    JSONB NOT NULL DEFAULT '{}'
);

CREATE FUNCTION audit_log_add_only() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  RAISE EXCEPTION 'The audit log is add-only: rows can''t be changed or deleted.';
END;
$$;

CREATE TRIGGER audit_log_add_only
BEFORE UPDATE OR DELETE OR TRUNCATE ON audit_log
FOR EACH STATEMENT EXECUTE FUNCTION audit_log_add_only();

ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
CREATE POLICY admins_read ON audit_log FOR SELECT TO authenticated USING ((SELECT private.my_role()) = 'admin');
GRANT SELECT ON audit_log TO authenticated;
GRANT SELECT ON audit_log TO service_role;

-- Writes audit entries (rows of the audit_log's own columns, as JSON).
CREATE FUNCTION private.add_audit(entries JSONB) RETURNS void
LANGUAGE sql SECURITY DEFINER SET search_path = '' AS $$
  INSERT INTO public.audit_log (at, actor_id, action, target_id, detail)
  SELECT COALESCE(at, now()), actor_id, action, target_id, COALESCE(detail, '{}')
  FROM jsonb_populate_recordset(NULL::public.audit_log, entries)
$$;
REVOKE EXECUTE ON FUNCTION private.add_audit(JSONB) FROM PUBLIC, anon, authenticated;

-- One account change: the people as they are now (new or changed), a new rep's row
-- if one was invited, and the audit entries. One transaction. "expect" holds each
-- changed person's status as the server saw it; if someone else changed them in
-- the meantime (two managers at once, two sign-ins at once), nothing is saved.
CREATE FUNCTION public.apply_account_change(change JSONB) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  PERFORM 1 FROM public.profiles p
  WHERE p.id IN (SELECT e.id FROM jsonb_to_recordset(COALESCE(change -> 'expect', '[]')) AS e (id TEXT, status TEXT))
  FOR UPDATE;
  IF EXISTS (
    SELECT 1 FROM jsonb_to_recordset(COALESCE(change -> 'expect', '[]')) AS e (id TEXT, status TEXT)
    JOIN public.profiles p ON p.id = e.id
    WHERE p.status <> e.status
  ) THEN
    RAISE EXCEPTION 'Someone changed this person a moment ago. Nothing was saved; look again and retry.';
  END IF;

  IF jsonb_typeof(change -> 'rep') = 'object' THEN
    INSERT INTO public.reps (id, name, store_id, hired_on)
    SELECT id, name, store_id, hired_on FROM jsonb_populate_record(NULL::public.reps, change -> 'rep');
  END IF;

  INSERT INTO public.profiles (id, auth_user_id, name, email, role, store_id, rep_id, status,
    invited_by, invited_at, activated_at, turned_off_at, turned_off_by)
  SELECT id, auth_user_id, name, email, role, store_id, rep_id, status,
    invited_by, invited_at, activated_at, turned_off_at, turned_off_by
  FROM jsonb_populate_recordset(NULL::public.profiles, change -> 'people')
  ON CONFLICT (id) DO UPDATE SET
    auth_user_id = COALESCE(excluded.auth_user_id, public.profiles.auth_user_id),
    name = excluded.name, email = excluded.email, role = excluded.role, store_id = excluded.store_id,
    rep_id = excluded.rep_id, status = excluded.status, invited_by = excluded.invited_by,
    invited_at = excluded.invited_at, activated_at = excluded.activated_at,
    turned_off_at = excluded.turned_off_at, turned_off_by = excluded.turned_off_by;

  PERFORM private.add_audit(change -> 'audit');
END;
$$;

-- The rules and the catalog, now with their audit entry in the same transaction.
DROP FUNCTION public.save_settings(JSONB);
CREATE FUNCTION public.save_settings(settings JSONB, audit JSONB) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  new_id BIGINT;
BEGIN
  INSERT INTO public.settings_history (changed_on, settings_json) VALUES (now(), settings) RETURNING id INTO new_id;
  PERFORM private.add_audit(audit);
  RETURN new_id;
END;
$$;

-- Step 6 of the import exactly as written (src/import/steps/6-apply.sql; a test
-- checks they match), run against the list an admin approved.
DROP FUNCTION public.apply_catalog_changes(JSONB);
CREATE FUNCTION public.apply_catalog_changes(changes JSONB, audit JSONB) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  n_changed INT;
  n_added INT;
BEGIN
  CREATE TEMP TABLE vendor_changes ON COMMIT DROP AS
  SELECT * FROM jsonb_to_recordset(changes) AS c (
    sku TEXT, model_sku TEXT, brand TEXT, model TEXT, category TEXT, size TEXT, change TEXT,
    new_list_cents INTEGER, new_cost_cents INTEGER, new_outlet_cost_cents INTEGER);
  SELECT COUNT(*) FILTER (WHERE change = 'changed'), COUNT(*) FILTER (WHERE change = 'new')
  INTO n_changed, n_added FROM vendor_changes;

  UPDATE products
  SET list_cents        = (SELECT c.new_list_cents        FROM vendor_changes c WHERE c.sku = products.sku),
      cost_cents        = (SELECT c.new_cost_cents        FROM vendor_changes c WHERE c.sku = products.sku),
      outlet_cost_cents = (SELECT c.new_outlet_cost_cents FROM vendor_changes c WHERE c.sku = products.sku),
      outlet_list_cents = (SELECT CASE WHEN c.new_outlet_cost_cents IS NULL THEN NULL
                                       ELSE CAST(ROUND(c.new_list_cents * 0.8) AS INTEGER) END
                           FROM vendor_changes c WHERE c.sku = products.sku)
  WHERE sku IN (SELECT sku FROM vendor_changes WHERE change = 'changed');

  INSERT INTO products (sku, model_sku, brand, model, category, size, list_cents, cost_cents,
                        outlet_list_cents, outlet_cost_cents)
  SELECT sku, model_sku, brand, model, category, size, new_list_cents, new_cost_cents,
         CASE WHEN new_outlet_cost_cents IS NULL THEN NULL ELSE CAST(ROUND(new_list_cents * 0.8) AS INTEGER) END,
         new_outlet_cost_cents
  FROM vendor_changes
  WHERE change = 'new';

  DROP TABLE vendor_changes;
  PERFORM private.add_audit(audit);
  RETURN jsonb_build_object('changed', n_changed, 'added', n_added);
END;
$$;

REVOKE EXECUTE ON FUNCTION public.apply_account_change(JSONB), public.save_settings(JSONB, JSONB),
  public.apply_catalog_changes(JSONB, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.apply_account_change(JSONB), public.save_settings(JSONB, JSONB),
  public.apply_catalog_changes(JSONB, JSONB) TO service_role;
