// Every report as a Postgres function, so live mode can run it through the API
// (supabase/migrations/*_report_functions.sql, written by `npm run
// db:report-functions`). Each one runs as the person asking (SECURITY INVOKER),
// so the access rules filter what it reads: a store manager's scorecard only
// contains their store, with no change to the report's SQL.
import { ALL_REPORTS, postgresFile, postgresSql } from './reports'

/** 'usage-company-by-month' → 'report_usage_company_by_month'. */
export function reportFunctionName(reportId: string): string {
  return `report_${reportId.replace(/-/g, '_')}`
}

/** The report's query without its header comments or final semicolon. */
function body(sql: string): string {
  return sql
    .split('\n')
    .filter((line) => !line.startsWith('--'))
    .join('\n')
    .trim()
    .replace(/;$/, '')
}

/** The whole migration: one function per report. */
export function reportFunctionsSql(): string {
  const parts = ALL_REPORTS.map((r) => {
    const name = reportFunctionName(r.id)
    return `-- ${r.title} (src/db/queries/${postgresFile(r)})
CREATE OR REPLACE FUNCTION public.${name}() RETURNS SETOF json
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = public AS $report$
SELECT row_to_json(r) FROM (
${body(postgresSql(r))}
) r
$report$;
REVOKE EXECUTE ON FUNCTION public.${name}() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.${name}() TO authenticated;
`
  })
  return `-- Generated by \`npm run db:report-functions\` from the report files; don't edit by hand.
-- Every report as a function that runs as the person asking, so the access rules
-- (row-level security) decide which rows it reads. Each row comes back as JSON,
-- with its columns in the report's order.

${parts.join('\n')}`
}
