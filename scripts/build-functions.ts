// Bundles the server function (server/save.ts) into supabase/functions/save/index.js
// for Supabase's Edge Functions runtime (Deno), so it shares the app's own engine
// and checks. Run by `npm run db:start`; the built file isn't kept in git.
import { build } from 'esbuild'

for (const name of ['save']) {
  await build({
    entryPoints: [`server/${name}.ts`],
    outfile: `supabase/functions/${name}/index.js`,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    banner: { js: '// Generated by scripts/build-functions.ts from server/. Don’t edit.' },
    logLevel: 'warning',
  })
  console.log(`Built supabase/functions/${name}/index.js`)
}
